package com.foreverfitness.fintess.dto;

import java.time.LocalDateTime;

public class WorkoutDTO {
    private Long id;
    private String title;
    private LocalDateTime startTime;
    private Integer durationMinutes;
    private Integer maxParticipants;
    private Long trainerId;
    private String trainerName;
    private Long workoutTypeId;
    private String workoutTypeName;

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public LocalDateTime getStartTime() {
        return startTime;
    }

    public void setStartTime(LocalDateTime startTime) {
        this.startTime = startTime;
    }

    public Integer getDurationMinutes() {
        return durationMinutes;
    }

    public void setDurationMinutes(Integer durationMinutes) {
        this.durationMinutes = durationMinutes;
    }

    public Integer getMaxParticipants() {
        return maxParticipants;
    }

    public void setMaxParticipants(Integer maxParticipants) {
        this.maxParticipants = maxParticipants;
    }

    public Long getTrainerId() {
        return trainerId;
    }

    public void setTrainerId(Long trainerId) {
        this.trainerId = trainerId;
    }

    public String getTrainerName() {
        return trainerName;
    }

    public void setTrainerName(String trainerName) {
        this.trainerName = trainerName;
    }

    public Long getWorkoutTypeId() {
        return workoutTypeId;
    }

    public void setWorkoutTypeId(Long workoutTypeId) {
        this.workoutTypeId = workoutTypeId;
    }

    public String getWorkoutTypeName() {
        return workoutTypeName;
    }

    public void setWorkoutTypeName(String workoutTypeName) {
        this.workoutTypeName = workoutTypeName;
    }

    public WorkoutDTO() {}
}
